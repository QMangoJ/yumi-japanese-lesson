/* Generate content-catalog.js — the key catalogue the admin
 * Site Content view renders (key -> section + human label).
 *
 * The front-end i18n keys ARE the English source strings, so the
 * catalogue is derived from i18n.js itself: sections come from the
 * grouping comments inside the dictionary literal (Object.assign
 * additions land in "Messages & placeholders"; the _STATIC_COPY_KEYS
 * block lands in "Static page copy"), and each label is the text an
 * English visitor actually sees (the en normalisation when one
 * exists, else the key itself).
 *
 * Run:  node scripts/gen-content-catalog.mjs
 * The output is committed; re-run after editing i18n.js. */
import { readFile, writeFile } from "node:fs/promises";
import vm from "node:vm";

const src = await readFile(new URL("../i18n.js", import.meta.url), "utf8");
const sandbox = { window: {} };
vm.createContext(sandbox);
vm.runInContext(src, sandbox);
const D = sandbox.window.YUMI_I18N;

const SECTION_NAMES = {
  "English normalisations for legacy mixed-language strings.": "Legacy mixed labels",
  "header / nav": "Header & navigation",
  "hero": "Hero",
  "upcoming-lessons calendar (task 1)": "Upcoming-lessons calendar",
  "sections": "Section headings",
  "about": "About",
  "lessons / courses": "Lessons & courses",
  "why": "Why Yumi (3 reasons)",
  "price": "Price",
  "book section": "Book section",
  "modal / picker": "Booking modal & date picker",
  "summary / my bookings": "Booking summary & My bookings",
  "account": "Account page",
  "packages (front)": "Lesson packages",
  "FAQ": "FAQ",
  "contact / footer / misc": "Contact, footer & misc",
};
const ADDITIONS = "Messages & placeholders";
const STATIC = "Static page copy (newly keyed)";

/* Walk the source: a slash-star comment sets the current section;
 * quoted keys at line start belong to it. Past the main literal
 * (first Object.assign) everything is "additions", except the
 * _STATIC_COPY_KEYS block which is the static-copy section. */
const keySection = new Map();
const sectionOrder = [];
let section = null;
let additions = false;
let inStatic = false;
const note = (name) => { if (!sectionOrder.includes(name)) sectionOrder.push(name); };
for (const line of src.split("\n")) {
  if (/_STATIC_COPY_KEYS/.test(line)) { inStatic = true; section = STATIC; note(section); continue; }
  if (/Object\.assign/.test(line) && !inStatic) additions = true;
  const cm = line.match(/\/\*\s*(.+?)\s*\*\//);
  if (cm && !additions && !inStatic && SECTION_NAMES[cm[1]]) {
    section = SECTION_NAMES[cm[1]]; note(section); continue;
  }
  const raws = inStatic
    ? [...line.matchAll(/^\s*"((?:[^"\\]|\\.)*)",?\s*$/g)]
    : [...line.matchAll(/"((?:[^"\\]|\\.)*)"\s*:/g)];
  for (const raw of raws) {
    let key = null;
    try { key = JSON.parse(`"${raw[1]}"`); } catch { key = null; }
    if (key && !keySection.has(key)) {
      keySection.set(key, inStatic ? STATIC : additions ? ADDITIONS : section || ADDITIONS);
      note(keySection.get(key));
    }
  }
}

const union = [...new Set([...Object.keys(D.en), ...Object.keys(D.zh), ...Object.keys(D.fr)])];
const entries = [];
const missing = [];
for (const key of union) {
  const s = keySection.get(key);
  if (!s) { missing.push(key); continue; }
  const enText = D.en[key] !== undefined ? D.en[key] : key;
  const label = enText.replace(/\s+/g, " ").trim();
  entries.push({ section: s, key, label: label.length > 90 ? label.slice(0, 89) + "…" : label });
}
if (missing.length) {
  console.error("keys without a section:", missing);
  process.exit(1);
}
entries.sort((a, b) => sectionOrder.indexOf(a.section) - sectionOrder.indexOf(b.section));

const out = `/* GENERATED by scripts/gen-content-catalog.mjs from i18n.js — do not edit by hand.
 * The key catalogue for the admin Site Content view: every front-end
 * i18n key (the English source strings), grouped by page section,
 * with the label an English visitor sees. Defaults live in i18n.js
 * (window.YUMI_I18N); this file only describes the keys. */
"use strict";
window.YUMI_CONTENT_CATALOG = ${JSON.stringify(entries, null, 1)};
`;
await writeFile(new URL("../content-catalog.js", import.meta.url), out);
console.log(`content-catalog.js: ${entries.length} keys in ${sectionOrder.length} sections`);
for (const s of sectionOrder) {
  console.log(`  ${s}: ${entries.filter((e) => e.section === s).length}`);
}
