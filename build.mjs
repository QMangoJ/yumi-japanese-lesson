/* Bundle the modular worker sources (src/) into the single-file
 * worker.js that deploy.py uploads and the harness imports.
 * Run:  node build.mjs        (requires the esbuild devDependency)
 * The output is committed, so what is tested is exactly what ships. */
import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";

await build({
  entryPoints: ["src/index.js"],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  outfile: "worker.js",
  banner: { js: "/* GENERATED by build.mjs from src/ — do not edit by hand. */" },
});
/* esbuild re-exports the entry's default as `export { x as default }`.
 * Rewrite it to a literal `export default x;` so the bundle keeps the
 * exact shape the original single-file worker had (the i18n harness
 * loads it with a string replace of "export default"). */
const src = await readFile("worker.js", "utf8");
const tail = src.match(/export \{\s*(\w+) as default\s*\};?\s*$/);
if (!tail) throw new Error("bundle tail export not found — esbuild output shape changed");
await writeFile("worker.js", src.slice(0, tail.index) + `export default ${tail[1]};\n`);
console.log("worker.js bundled from src/");
